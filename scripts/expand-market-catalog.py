"""Build the shared requested catalog, preserving the original matrix order."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
matrix = ROOT / 'src/components/arbitrage/PairMatrix100.tsx'
text = matrix.read_text(encoding='utf-8')
requested = json.loads((ROOT / 'src/config/requested-market-pairs.json').read_text())
legacy = re.findall(r'symbol: "([A-Z0-9]+/[A-Z0-9]+)"', text)
catalog_path = ROOT / 'src/config/market-pairs.json'
existing = json.loads(catalog_path.read_text()) if catalog_path.exists() else legacy
symbols = list(dict.fromkeys([*existing, 'ETH/USD', 'BTC/USD', 'SOL/USD', 'SEI/USD', 'PEPE/USD', *requested]))
assert all(re.fullmatch(r'[A-Z0-9]+/[A-Z0-9]+', p) and len(set(p.split('/'))) == 2 for p in symbols)
catalog_path.write_text(json.dumps(symbols, indent=2) + '\n', encoding='utf-8')
out = ROOT / 'config'
out.mkdir(exist_ok=True)
(out / 'market-pairs.env').write_text(
    '# Generated by scripts/expand-market-catalog.py. Requested markets; venue listing is checked at runtime.\n'
    + '\n'.join(f'{key}={json.dumps(symbols, separators=(",", ":"))}' for key in ['CS_STREAM_SYMBOLS', 'MD_PAIRS', 'ARB_SYMBOLS']) + '\n', encoding='utf-8')
print(f'{len(symbols)} unique requested markets ({len(requested)} in the supplied expansion).')
