import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const outDir = path.resolve(root, "contracts/out");
const targetDir = path.resolve(root, "src/lib/launchpad");

if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const contracts = [
  "GovernanceToken",
  "FeeDiscountStaking",
  "YieldStakingVault",
  "CompoundYieldVault",
  "IsolatedLendingVault",
  "AaveFlashBorrower",
];

const contractData = {};

for (const name of contracts) {
  const jsonPath = path.resolve(outDir, `${name}.json`);
  if (!fs.existsSync(jsonPath)) {
    console.error(`Artifact not found: ${jsonPath}`);
    process.exit(1);
  }
  const data = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  contractData[name] = {
    abi: data.abi,
    bytecode: data.bytecode,
  };
}

const fileContent = `// src/lib/launchpad/artifacts.ts
// Auto-generated by scripts/generate-launchpad-artifacts.mjs
// DO NOT EDIT DIRECTLY

import type { Abi, Hex } from "viem";

export interface ContractArtifact {
  readonly abi: Abi;
  readonly bytecode: Hex;
}

export const LAUNCHPAD_ARTIFACTS = {
  GovernanceToken: {
    abi: ${JSON.stringify(contractData.GovernanceToken.abi)} as unknown as Abi,
    bytecode: "${contractData.GovernanceToken.bytecode}" as Hex,
  },
  FeeDiscountStaking: {
    abi: ${JSON.stringify(contractData.FeeDiscountStaking.abi)} as unknown as Abi,
    bytecode: "${contractData.FeeDiscountStaking.bytecode}" as Hex,
  },
  YieldStakingVault: {
    abi: ${JSON.stringify(contractData.YieldStakingVault.abi)} as unknown as Abi,
    bytecode: "${contractData.YieldStakingVault.bytecode}" as Hex,
  },
  CompoundYieldVault: {
    abi: ${JSON.stringify(contractData.CompoundYieldVault.abi)} as unknown as Abi,
    bytecode: "${contractData.CompoundYieldVault.bytecode}" as Hex,
  },
  IsolatedLendingVault: {
    abi: ${JSON.stringify(contractData.IsolatedLendingVault.abi)} as unknown as Abi,
    bytecode: "${contractData.IsolatedLendingVault.bytecode}" as Hex,
  },
  AaveFlashBorrower: {
    abi: ${JSON.stringify(contractData.AaveFlashBorrower.abi)} as unknown as Abi,
    bytecode: "${contractData.AaveFlashBorrower.bytecode}" as Hex,
  },
} as const;
`;

fs.writeFileSync(path.resolve(targetDir, "artifacts.ts"), fileContent, "utf8");
console.log("Successfully generated src/lib/launchpad/artifacts.ts");
